"""Generates docs/markdown-compat.md from tests/markdown_cases.py.

"Before" is the renderer from a git revision (default: the commit before the 2026-10 audit, 9dcf095);
"After" is the current one. Usage:
    .venv\\Scripts\\python.exe scripts\\gen_markdown_compat.py [--before-rev 9dcf095]
"""

from __future__ import annotations

import argparse
import ast
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "tests"))

from markdown_cases import CASES  # noqa: E402
from pdf_notes_reader.markdown_render import render_markdown_body  # noqa: E402

OLD_NAMES = {"MATH_BLOCK_RE", "MATH_INLINE_RE", "CODE_SEGMENT_RE", "LATEX_SYMBOLS", "latex_to_html",
             "protect_code_segments", "restore_placeholders", "render_markdown_preview"}


def load_old_renderer(rev: str):
    source = subprocess.run(
        ["git", "show", f"{rev}:src/pdf_notes_reader/main.py"], cwd=ROOT, capture_output=True, check=True
    ).stdout.decode("utf-8")
    tree = ast.parse(source)
    keep = [
        node
        for node in tree.body
        if (isinstance(node, (ast.FunctionDef,)) and node.name in OLD_NAMES)
        or (isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name) and node.targets[0].id in OLD_NAMES)
    ]
    module = ast.Module(body=keep, type_ignores=[])
    namespace: dict = {}
    exec("import html, re, markdown", namespace)  # noqa: S102 - our own source from git
    exec(compile(module, f"{rev}:main.py", "exec"), namespace)  # noqa: S102
    return namespace["render_markdown_preview"]


def check(case, body: str) -> tuple[bool, str]:
    present = [item for item in case.expect if item in body]
    rejected = [item for item in case.reject if item in body]
    ok = len(present) == len(case.expect) and not rejected
    if case.category == "LaTeX symbols":
        return ok, f"{len(present)}/{len(case.expect)}"
    return ok, ""


def status(ok: bool, supported: bool, detail: str) -> str:
    if not supported:
        return "No (known gap)"
    mark = "Yes" if ok else "No"
    return f"{mark} {detail}".strip()


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--before-rev", default="9dcf095")
    args = parser.parse_args()
    old_render = load_old_renderer(args.before_rev)

    lines = [
        "# Markdown and LaTeX compatibility matrix",
        "",
        "Generated by `scripts/gen_markdown_compat.py` from `tests/markdown_cases.py`; enforced by",
        "`tests/test_markdown_compat.py`. **Before** = PDFNest 0.2.5 (`" + args.before_rev + "`), **After** = this version.",
        "Symbol rows count how many symbols of the category render (not as raw `\\name`).",
        "",
        "Rendering target is Qt rich text (`QTextBrowser`): no MathJax/KaTeX. Display math uses nested tables for",
        "stacked fractions, matrices, cases and limits; inline math stays on one line (`a⁄b` style fractions).",
        "",
    ]
    category = None
    for case in CASES:
        if case.category != category:
            category = case.category
            lines += ["", f"## {category}", "", "| Feature | Example | Before | After | Notes |", "|---|---|---|---|---|"]
        try:
            before_ok, before_detail = check(case, old_render(case.source))
        except Exception as exc:  # the old renderer crashed on this input
            before_ok, before_detail = False, f"(error: {type(exc).__name__})"
        after_ok, after_detail = check(case, render_markdown_body(case.source))
        example = case.source if len(case.source) <= 60 else case.source[:57] + "..."
        example = example.replace("|", "\\|").replace("\n", "↵")
        lines.append(
            f"| {case.feature} | `{example}` | {status(before_ok, case.supported, before_detail)} | "
            f"{status(after_ok, case.supported, after_detail)} | {case.note} |"
        )
    target = ROOT / "docs" / "markdown-compat.md"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {target.relative_to(ROOT)} ({len(CASES)} cases)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
